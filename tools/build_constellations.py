"""
build_constellations.py
=======================

Turns the raw constellation data in data/raw/ into data/constellations.js:
the stick-figure lines that join stars into shapes like Orion, plus each
constellation's full name and the middle of its figure.

How to run it (from the project folder, in a terminal):
    python tools/build_constellations.py      (on Windows you may need: py tools/build_constellations.py)
"""

import json
from pathlib import Path

PROJECT = Path(__file__).parent.parent
RAW_LINES = PROJECT / "data" / "raw" / "constellations.lines.json"
RAW_INFO = PROJECT / "data" / "raw" / "constellations.json"
OUTPUT = PROJECT / "data" / "constellations.js"


def load_json(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def to_hours(longitude):
    """Map-style longitude (-180..180 degrees) -> right ascension (0..24 hours). 15 degrees = 1 hour."""
    return round((longitude % 360) / 15, 4)


def build(lines_data, info_data):
    """
    Collect everything about each constellation into one dictionary, keyed by its
    3-letter code. A dictionary is like a labeled box: constellations["Ori"] -> Orion's data.
    """
    constellations = {}

    # Names and centers. Serpens is split into two parts (head and tail) in the
    # data, so we keep the first center and call it plain "Serpens".
    for feature in info_data["features"]:
        code = feature["id"]
        if code in constellations:
            continue
        name = feature["properties"]["name"]
        if code == "Ser":
            name = "Serpens"
        lon, lat = feature["properties"].get("display", feature["geometry"]["coordinates"])[:2]
        constellations[code] = {"id": code, "name": name, "center": [to_hours(lon), round(lat, 2)], "lines": []}

    # Stick-figure lines. Each line is a list of points: [right ascension, declination].
    for feature in lines_data["features"]:
        code = feature["id"]
        for line in feature["geometry"]["coordinates"]:
            constellations[code]["lines"].append([[to_hours(lon), round(lat, 3)] for lon, lat in line])

    # Turn the dictionary into a list sorted by name.
    return sorted(constellations.values(), key=lambda c: c["name"])


def write_js(items, path):
    header = """// Constellations for Overhead (generated by tools/build_constellations.py, do not edit by hand)
// Each entry: id (3-letter code), name, center [RA hours, Dec degrees], lines (stick figure).
// Data from d3-celestial by Olaf Frohn (BSD-3-Clause, see data/LICENSE-d3-celestial.txt).
const CONSTELLATIONS = """
    path.write_text(header + json.dumps(items, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")


if __name__ == "__main__":
    items = build(load_json(RAW_LINES), load_json(RAW_INFO))
    write_js(items, OUTPUT)
    segments = sum(len(line) - 1 for c in items for line in c["lines"])
    print(f"Wrote {len(items)} constellations with {segments} line segments to {OUTPUT}")
    print("A few:", ", ".join(c["name"] for c in items[:5]), "...")
